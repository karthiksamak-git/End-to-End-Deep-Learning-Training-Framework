"""Generate ``notebooks/eda.ipynb`` from a single source of truth.

The notebook is written as plain JSON (no nbformat dependency) so it stays in sync
with the framework, and ``--execute`` runs every code cell to prove it works.

Usage:
    python scripts/build_eda_notebook.py            # write the notebook
    python scripts/build_eda_notebook.py --execute  # write it and run all cells
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

MARKDOWN_1 = """# Exploratory data analysis — Breast Cancer (tabular task)

Generated by `scripts/build_eda_notebook.py`. It uses the same code path as
`dltf train --config configs/tabular_mlp.yaml`, so what you see here is what the
model sees: a median imputer + standard scaler fitted **only** on the training
split."""

CODE_1 = """import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from dltf.data.splits import stratified_split
from dltf.data.tabular import build_eda, load_tabular_frame
from dltf.seed import set_seed

set_seed(42)
frame = load_tabular_frame("breast_cancer")
df = frame.as_frame()
print(f"{df.shape[0]} rows, {df.shape[1] - 1} features, classes: {frame.class_names}")
df.head()"""

MARKDOWN_2 = """## Splits and class balance

Stratified 70/15/15 split, identical to training (seed 42). Every class keeps its
proportion in each split."""

CODE_2 = """split = stratified_split(frame.y, val_fraction=0.15, test_fraction=0.15, seed=42)
balance = pd.DataFrame(
    {
        name: np.bincount(frame.y[idx], minlength=frame.num_classes)
        for name, idx in split.items()
    },
    index=frame.class_names,
)
print("split sizes:", {k: int(v.size) for k, v in split.items()})
balance"""

MARKDOWN_3 = """## Missing values and correlations

The EDA helper writes a JSON summary plus PNG figures into `artifacts/eda/`."""

CODE_3 = """summary = build_eda(frame, "artifacts/eda")
print("missing values:", summary["n_missing_total"])
print("duplicate rows:", summary["duplicate_rows"])
print("class balance:", summary["class_balance"])

top = pd.Series(summary["top_correlated_with_target"]).sort_values(key=np.abs, ascending=False)
top.head(8)"""

MARKDOWN_4 = """## Leakage check

Standardisation statistics are fitted on the training rows only. If we accidentally
fitted on the whole dataset the two mean vectors below would be identical."""

CODE_4 = """from sklearn.preprocessing import StandardScaler

train = split["train"]
scaler = StandardScaler().fit(frame.X[train])
print("train-only mean (first 5):", np.round(scaler.mean_[:5], 4))
print("full-data mean (first 5):", np.round(frame.X.mean(axis=0)[:5], 4))
assert not np.allclose(scaler.mean_, frame.X.mean(axis=0)), "leakage detected"
print("no leakage: train-only statistics differ from full-data statistics")

plt.close("all")"""

CELLS = [
    ("markdown", MARKDOWN_1),
    ("code", CODE_1),
    ("markdown", MARKDOWN_2),
    ("code", CODE_2),
    ("markdown", MARKDOWN_3),
    ("code", CODE_3),
    ("markdown", MARKDOWN_4),
    ("code", CODE_4),
]


def build_notebook() -> dict:
    """Return the notebook as an nbformat-4 dict."""
    cells = []
    for kind, source in CELLS:
        if kind == "markdown":
            cells.append({"cell_type": "markdown", "metadata": {}, "source": source.splitlines(True)})
        else:
            cells.append(
                {
                    "cell_type": "code",
                    "execution_count": None,
                    "metadata": {},
                    "outputs": [],
                    "source": source.splitlines(True),
                }
            )
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.12"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def execute_cells(workdir: Path) -> None:
    """Run every code cell in order, exactly like ``Run All`` would."""
    import os

    os.chdir(workdir)
    namespace: dict = {"__name__": "__main__"}
    for index, (kind, source) in enumerate(CELLS, start=1):
        if kind != "code":
            continue
        print(f"--- executing cell {index} ---")
        exec(compile(source, f"<notebook cell {index}>", "exec"), namespace)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--execute", action="store_true", help="run every code cell")
    parser.add_argument("--out", default="notebooks/eda.ipynb")
    args = parser.parse_args()

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(build_notebook(), indent=1) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(CELLS)} cells)")
    if args.execute:
        execute_cells(ROOT)
        print("notebook executed cleanly")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
