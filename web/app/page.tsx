import Link from "next/link";

import {
  Badge,
  Card,
  DataTable,
  EmptyState,
  PageHeader,
  SectionTitle,
  Stat,
  formatCount,
  formatNumber,
  formatPct,
  formatSeconds,
} from "@/components/ui";
import { getHeadline, getModelCard, getRuns } from "@/lib/data";

export const dynamic = "force-static";

const PIPELINE = [
  { step: "01", title: "Data", detail: "sklearn + Fashion-MNIST, stratified splits, leak-free preprocessing" },
  { step: "02", title: "Models", detail: "Custom MLP and residual CNN, registered and shape-tested" },
  { step: "03", title: "Training", detail: "AMP when CUDA, clipping, schedulers, early stopping, resume" },
  { step: "04", title: "HPO", detail: "Optuna TPE with median pruning, fully seeded" },
  { step: "05", title: "Evaluation", detail: "5-fold CV, confusion matrix, calibration, error analysis" },
  { step: "06", title: "Export", detail: "ONNX opset 17 with parity check, JSON artifacts" },
  { step: "07", title: "Web", detail: "This dashboard + browser inference with onnxruntime-web" },
];

export default async function OverviewPage() {
  const [headline, card, runs] = await Promise.all([getHeadline(), getModelCard(), getRuns()]);

  if (!card) {
    return (
      <>
        <PageHeader
          eyebrow="Overview"
          title="Experiment dashboard"
          description="Static artifacts generated by the training pipeline."
        />
        <EmptyState
          title="No artifacts yet"
          detail="Run the pipeline to generate web/public/data/*.json and the ONNX model."
        />
      </>
    );
  }

  const imageRun = runs.find((run) => run.task === "image");
  const tabularRun = runs.find((run) => run.task === "tabular");
  const width = (card.architecture.config?.width as number | undefined) ?? 32;
  const depth = (card.architecture.config?.depth as number | undefined) ?? 2;

  return (
    <>
      <PageHeader
        eyebrow="End-to-end deep learning"
        title="Every number here came from a real run"
        description="A PyTorch framework covering the full model lifecycle — preprocessing, custom architectures, training with AMP and checkpointing, Optuna search, stratified k-fold cross-validation, error analysis and ONNX export. The dashboard renders the artifacts those runs produced; the playground runs the exported network in your browser."
      />

      <section className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <Stat
          label="Image CNN · test accuracy"
          value={formatPct(headline?.test_accuracy)}
          sub={`macro F1 ${formatPct(headline?.test_f1_macro)}`}
          accent
        />
        <Stat
          label="Breast cancer · 5-fold CV"
          value={formatPct(headline?.cv_accuracy_mean)}
          sub={`± ${((headline?.cv_accuracy_std ?? 0) * 100).toFixed(2)} pts across folds`}
        />
        <Stat
          label={`HPO best ${headline?.hpo_metric ?? "val_f1"}`}
          value={formatNumber(headline?.hpo_best_value, 4)}
          sub={`${card.onnx.size_mb ?? "—"} MB ONNX, ${card.onnx.opset ?? 17} opset`}
        />
        <Stat
          label="Parameters"
          value={formatCount(card.architecture.parameters_total)}
          sub={`${formatSeconds(card.training.duration_sec)} training on ${card.device.device ?? "cpu"}`}
        />
      </section>

      <section className="mt-10">
        <SectionTitle
          title="Lifecycle"
          hint="One CLI drives all of it: dltf train | cv | hpo | analyze | export | all"
        />
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {PIPELINE.map((item) => (
            <Card key={item.step} className="p-4">
              <p className="font-mono text-xs text-indigo-600 dark:text-indigo-400">{item.step}</p>
              <p className="mt-1 font-semibold">{item.title}</p>
              <p className="muted mt-1 leading-relaxed">{item.detail}</p>
            </Card>
          ))}
        </div>
      </section>

      <section className="mt-10 grid gap-6 lg:grid-cols-5">
        <Card className="lg:col-span-3">
          <SectionTitle
            title="Model card"
            hint="Written by dltf export from the checkpoint that produced the ONNX file"
          />
          <DataTable
            head={["Field", "Value"]}
            rows={[
              ["Dataset", card.dataset.name ?? "—"],
              [
                "Splits (train / val / test)",
                `${formatCount(card.dataset.train_size)} / ${formatCount(card.dataset.val_size)} / ${formatCount(card.dataset.test_size)}`,
              ],
              ["Architecture", `${card.architecture.class} · ${formatCount(card.architecture.parameters_total)} params`],
              ["Seed", String(card.seed ?? "—")],
              ["Device", `${card.device.device ?? "cpu"}${card.device.supports_amp ? " (AMP available)" : ""}`],
              ["Optimizer", `${card.training.optimizer ?? "—"} · lr ${card.training.lr ?? "—"}`],
              ["Scheduler", card.training.scheduler ?? "—"],
              ["Batch size", String(card.training.batch_size ?? "—")],
              ["Epochs", String(card.training.epochs_run ?? "—")],
              ["Test accuracy", formatPct(card.metrics.accuracy)],
              ["Test macro F1", formatPct(card.metrics.f1_macro)],
              [
                "ONNX parity",
                `${
                  card.onnx_parity.max_abs_diff !== undefined
                    ? card.onnx_parity.max_abs_diff.toExponential(2)
                    : "—"
                } max abs diff (${card.onnx_parity.passed ? "passed" : "FAILED"})`,
              ],
              ["Git commit", card.git_hash ? card.git_hash.slice(0, 8) : "—"],
            ]}
          />
        </Card>

        <div className="space-y-6 lg:col-span-2">
          <Card>
            <SectionTitle
              title="Architecture"
              hint={`ResNetSmall: 3 stages · ${depth} residual blocks each`}
            />
            <ol className="space-y-2 text-sm">
              {[
                "Input 1×28×28 (Fashion-MNIST)",
                "Augment: rotation ±10°, translation ±10% (train only)",
                "Normalize with train-split mean/std",
                "Stem 3×3 conv → BatchNorm → ReLU",
                `Stages ${width} → ${width * 2} → ${width * 4} channels, stride-2 downsampling`,
                "Residual blocks: conv-BN-ReLU-conv-BN + shortcut",
                "Global average pooling → dropout → linear (10 classes)",
              ].map((line) => (
                <li key={line} className="flex gap-2">
                  <span className="mt-1 h-1.5 w-1.5 shrink-0 rounded-full bg-indigo-500" />
                  <span className="leading-relaxed">{line}</span>
                </li>
              ))}
            </ol>
          </Card>

          <Card>
            <SectionTitle title="Runs" hint="Committed to git as summary JSON" />
            {runs.length === 0 ? (
              <p className="muted">No runs recorded.</p>
            ) : (
              <ul className="space-y-3 text-sm">
                {runs.map((run) => (
                  <li key={run.id} className="flex min-w-0 items-center justify-between gap-3">
                    <div className="min-w-0">
                      <p className="truncate font-medium">{run.name}</p>
                      <p className="muted truncate font-mono text-xs">{run.id}</p>
                    </div>
                    <div className="flex shrink-0 items-center gap-2">
                      <Badge tone={run.task === "image" ? "info" : "good"}>{run.task}</Badge>
                      <span className="text-xs tabular-nums">
                        {formatPct(run.test_metrics.accuracy)}
                      </span>
                    </div>
                  </li>
                ))}
              </ul>
            )}
            <div className="mt-4 flex flex-wrap gap-2">
              <Link href="/experiments" className="btn-ghost">
                Training curves
              </Link>
              <Link href="/playground" className="btn-primary">
                Try the model
              </Link>
            </div>
          </Card>
        </div>
      </section>

      <section className="mt-10 grid gap-4 sm:grid-cols-2">
        <Card>
          <SectionTitle title="Tabular model" hint="Breast Cancer, 30 features, 397/86/86 split" />
          <p className="muted">
            MLP 30→64→32→2 with BatchNorm and dropout, standardized with statistics fitted on the
            training rows only.
          </p>
          <p className="mt-3 text-sm">
            Held-out accuracy{" "}
            <span className="font-semibold">{formatPct(tabularRun?.test_metrics.accuracy)}</span> ·
            ROC-AUC{" "}
            <span className="font-semibold">{formatNumber(tabularRun?.test_metrics.roc_auc ?? null, 4)}</span>
          </p>
        </Card>
        <Card>
          <SectionTitle title="Known limitations" hint="Honest scope" />
          <ul className="muted list-disc space-y-1 pl-4">
            {card.limitations.map((line) => (
              <li key={line}>{line}</li>
            ))}
            {imageRun ? (
              <li>
                Image run: {formatCount(imageRun.sizes.train)} train /{" "}
                {formatCount(imageRun.sizes.val)} val / {formatCount(imageRun.sizes.test)} test
                samples, {imageRun.epochs_run} epochs.
              </li>
            ) : null}
          </ul>
        </Card>
      </section>
    </>
  );
}
